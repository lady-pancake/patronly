// Writes src/environments/environment.ts from environment variables.
// Runs before `start`, `build` and `test` (see package.json), so Vercel can
// inject the backend URL at build time with NG_APP_GRAPHQL_URL.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Load frontend/.env for local development, without overriding real env vars.
const envFile = resolve(root, '.env');
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split('\n')) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match && process.env[match[1]] === undefined) {
      process.env[match[1]] = match[2].replace(/^['"]|['"]$/g, '');
    }
  }
}

const environment = {
  production: process.env.NODE_ENV === 'production' || !!process.env.VERCEL,
  graphqlUrl: process.env.NG_APP_GRAPHQL_URL || 'http://localhost:8000/graphql',
};

const target = resolve(root, 'src/environments/environment.ts');
writeFileSync(
  target,
  `// AUTO-GENERATED by scripts/set-env.mjs. Do not edit or commit.\n` +
    `export const environment = ${JSON.stringify(environment, null, 2)} as const;\n`,
);
console.log(`[set-env] graphqlUrl=${environment.graphqlUrl}`);
